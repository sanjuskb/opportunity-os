def build_records() -> dict[str, object]:
    records: list[dict[str, object]] = []
    for idx, item in enumerate(SPECS, start=1):
        edu_yr, branch, skills, interest, summary = item["stu"]  # type: ignore[misc]
        pos_title, pos_org, pos_desc, pos_req, pos_yrs = item["pos"]  # type: ignore[misc]
        neg_title, neg_org, neg_dom, neg_desc, neg_req, neg_yrs = item["neg"]  # type: ignore[misc]
        pair_id = str(item["pair_id"])
        split = str(item["split"])
        domain = str(item["domain"])

        records.append(
            {
                "pair_id": pair_id,
                "split": split,
                "relevance_label": 1,
                "is_synthetic": True,
                "student": {
                    "student_id": f"cur2-st-{split}-{idx:03d}",
                    "education_year": edu_yr,
                    "branch": branch,
                    "skills": skills,
                    "career_interest": interest,
                    "profile_summary": summary,
                    "preferred_languages": ["en"],
                },
                "opportunity": {
                    "opportunity_id": f"cur2-opp-pos-{split}-{idx:03d}",
                    "title": pos_title,
                    "organization": pos_org,
                    "domain_family": domain,
                    "description": pos_desc,
                    "required_skills": pos_req,
                    "eligible_years": pos_yrs,
                },
                "hard_negative_opportunity": {
                    "opportunity_id": f"cur2-opp-hn-{split}-{idx:03d}",
                    "title": neg_title,
                    "organization": neg_org,
                    "domain_family": neg_dom,
                    "description": neg_desc,
                    "required_skills": neg_req,
                    "eligible_years": neg_yrs,
                },
            }
        )

    return {
        "dataset_name": "nexteras_synthetic_matching_curriculum_v2",
        "version": "2.0.0",
        "is_synthetic": True,
        "provenance": (
            "Authored expanded contrastive synthetic dataset (48 train / 16 val / 24 untouched held-out test triplets) "
            "bridging Indian student project terminology to formal opportunity roles alongside adversarial cross-track "
            "keyword-sharing hard negatives. Explicitly synthetic — zero real student PII or production click logs."
        ),
        "known_limitations": [
            "All student bios and opportunity postings are synthetic; production performance requires telemetry from live portals.",
            "Hard negatives use domain_family-disjoint keyword traps to eliminate false-negative ambiguity; within-domain seniority nuances need real recruiter labels.",
        ],
        "records": records,
    }


def main() -> None:
    out_path = REPO_ROOT / "ml" / "datasets" / "synthetic" / "matching_curriculum_v2.json"
    payload = build_records()
    out_path.write_text(json.dumps(payload, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    loaded = load_seed_records(out_path)
    validate_no_split_leakage(loaded)
    from collections import Counter

    print(f"Wrote {len(loaded)} validated triplets to {out_path}")
    print("Splits:", Counter(r.split for r in loaded))
    print("Domains in test:", Counter(r.opportunity.domain_family for r in loaded if r.split == "test"))


if __name__ == "__main__":
    main()
